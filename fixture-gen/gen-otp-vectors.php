<?php

/**
 * OTP parity-vector generator — runs the SERVER's authoritative OTP stack
 * (spomky-labs/otphp + doctormckay/steam-totp, the exact implementations
 * TwoFAccount.php:515-536 delegates to) to produce test vectors for the CLI.
 *
 * One-off tooling for 2FA-Vault-CLI phase 1 (plan 261007-2255, RT-3):
 * fixtures must come from the real implementations, never from the code
 * under test. Run from the app repo root:
 *
 *   php fixture-gen/gen-otp-vectors.php > ../2FA-Vault-CLI/src/fixtures/otp-vectors.json
 *
 * Server construction mirrored from TwoFAccount::initGenerator():
 *   TOTP  = TOTP::create(secret, period, algorithm, digits)
 *   HOTP  = HOTP::create(secret, counter, algorithm, digits)
 *   Steam = SteamTotp::getAuthCode(base64_encode(Base32::decodeUpper(secret)))
 */

require __DIR__ . '/../vendor/autoload.php';

use OTPHP\TOTP;
use OTPHP\HOTP;
use ParagonIE\ConstantTime\Base32;
use SteamTotp\SteamTotp;

/** The account secrets, exactly as stored in `twofaccounts.secret` (base32). */
$secrets = [
    'GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ', // RFC 6238 ref: "12345678901234567890"
    'JBSWY3DPEHPK3PXP',                 // classic demo secret ("Hello!\xde\xad\xbe\xef")
    'MFRGGZDFMZTWQ2LKNNWG23TPM6A7A7K',  // 20 random-ish bytes, no padding
];

$algorithms = ['sha1', 'sha256', 'sha512'];
$times = [59, 1111111109, 1234567890];
$counters = [0, 1, 999];

$totp = [];
foreach ($secrets as $secret) {
    foreach ($algorithms as $algorithm) {
        foreach ([6, 8] as $digits) {
            foreach ([30, 60] as $period) {
                $generator = TOTP::create($secret, $period, $algorithm, $digits);
                foreach ($times as $at) {
                    $totp[] = [
                        'secret' => $secret,
                        'algorithm' => $algorithm,
                        'digits' => $digits,
                        'period' => $period,
                        'at' => $at,
                        'code' => $generator->at($at),
                    ];
                }
            }
        }
    }
}

$hotp = [];
foreach ($secrets as $secret) {
    foreach ($algorithms as $algorithm) {
        foreach ([6, 8] as $digits) {
            $generator = HOTP::create($secret, 0, $algorithm, $digits);
            foreach ($counters as $counter) {
                $hotp[] = [
                    'secret' => $secret,
                    'algorithm' => $algorithm,
                    'digits' => $digits,
                    'counter' => $counter,
                    'code' => $generator->at($counter),
                ];
            }
        }
    }
}

$steam = [];
foreach ($secrets as $secret) {
    // SteamTotp uses time() internally; getAuthCode's $time_offset shifts it.
    // Offset = targetTime - now reproduces `floor(targetTime / 30)` exactly.
    foreach ([1717171717, 1234567890] as $targetTime) {
        $steam[] = [
            'secret' => $secret,
            'at' => $targetTime,
            'code' => SteamTotp::getAuthCode(
                base64_encode(Base32::decodeUpper($secret)),
                $targetTime - time()
            ),
        ];
    }
}

echo json_encode([
    '_provenance' => 'Generated by 2FA-Vault/fixture-gen/gen-otp-vectors.php against spomky-labs/otphp + doctormckay/steam-totp (the server OTP stack used by TwoFAccount::initGenerator). Regenerate from the app repo root: php fixture-gen/gen-otp-vectors.php',
    'generated_at' => date('c'),
    'totp' => $totp,
    'hotp' => $hotp,
    'steam' => $steam,
], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . PHP_EOL;
